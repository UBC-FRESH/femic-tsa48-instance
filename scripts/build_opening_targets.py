#!/usr/bin/env python
"""Add the opening-size policy targets to a TSA 48 targets file.

The policy is the MKRF staff guidance recorded for the North Island work:
openings at or below 1 ha and above 50 ha are excluded, 1-5 ha is capped at
10% of opening area, and 40-50 ha at 5%. The 5-40 ha class has no target.

The shares are confirmed as **ceilings** (MKRF staff, October 2026). The
Very High/High numeric weights remain an implementation calibration.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

DEFAULT_PERIODS = 10
DEFAULT_PERIOD_WIDTH = 10
PATCH_CLASSES: tuple[tuple[str, float, float], ...] = (
    ("patch.grpblk.0_1.size", 0.0, 10_000_000.0),
    ("patch.grpblk.1_5.size", 10.0, 1_000_000.0),
    ("patch.grpblk.40_50.size", 5.0, 1_000_000.0),
    ("patch.grpblk.50_9999999.size", 0.0, 1_000_000.0),
)


def opening_targets(
    *, periods: int = DEFAULT_PERIODS, period_width: int = DEFAULT_PERIOD_WIDTH
) -> list[dict[str, object]]:
    """Return the opening-size targets for each accounting period.

    Parameters
    ----------
    periods : int
        Number of accounting periods.
    period_width : int
        Width of each period, in years.

    Returns
    -------
    list of dict
        Targets in the optimizer's YAML row shape.
    """
    rows: list[dict[str, object]] = []
    for period in range(1, periods + 1):
        for account, maximum, weight in PATCH_CLASSES:
            rows.append(
                {
                    "account": account,
                    "period": period,
                    "period_width": period_width,
                    "maximum": maximum,
                    "max_weight": weight,
                    "notes": (
                        "opening-size policy, maxima assumption; Very High=1,000,000, High=100,000"
                    ),
                }
            )
    return rows


def combine_targets(
    base: Path,
    *,
    periods: int = DEFAULT_PERIODS,
    period_width: int = DEFAULT_PERIOD_WIDTH,
) -> list[dict[str, object]]:
    """Return the base targets followed by the opening-size targets.

    Parameters
    ----------
    base : Path
        The existing AAC targets YAML.
    periods : int
        Number of accounting periods.
    period_width : int
        Width of each period, in years.

    Returns
    -------
    list of dict
        Combined target rows.
    """
    document = yaml.safe_load(base.read_text(encoding="utf-8"))
    rows = list(document.get("targets", []))
    if not rows:
        raise ValueError(f"{base} has no targets")
    return rows + opening_targets(periods=periods, period_width=period_width)


def main() -> None:
    """Write the combined AAC plus opening targets."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--periods", type=int, default=DEFAULT_PERIODS)
    parser.add_argument("--period-width", type=int, default=DEFAULT_PERIOD_WIDTH)
    args = parser.parse_args()
    rows = combine_targets(args.base, periods=args.periods, period_width=args.period_width)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# Generated by scripts/build_opening_targets.py.\n"
        "# The opening shares are MAXIMA under the current MKRF assumption;\n"
        "# confirm maximum-vs-minimum and the Very High/High weights before release.\n"
    )
    args.out.write_text(
        header + yaml.safe_dump({"targets": rows}, sort_keys=False), encoding="utf-8"
    )
    print(f"wrote {len(rows)} targets to {args.out}")


if __name__ == "__main__":
    main()
